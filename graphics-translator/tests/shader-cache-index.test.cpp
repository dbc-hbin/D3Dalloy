  require(GetTempPathW(MAX_PATH, directory) && GetTempFileNameW(directory, L"sc", 0, path), "unique file");
  D3D12_SHADER_CACHE_SESSION_DESC desc{};
  desc.Mode = D3D12_SHADER_CACHE_MODE_DISK;
