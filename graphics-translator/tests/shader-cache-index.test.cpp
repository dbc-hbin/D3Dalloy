uint64_t read_bytes = 0;
unsigned failed_flushes = 0;
unsigned failed_writes = 0;
BOOL injected_write(HANDLE file, const void *data, DWORD size, DWORD *done, OVERLAPPED *overlapped) {
  if (failed_writes) { --failed_writes; *done = 0; SetLastError(ERROR_WRITE_FAULT); return FALSE; }
  return WriteFile(file, data, size, done, overlapped);
}
BOOL counted_read(HANDLE file, void *data, DWORD size, DWORD *done, OVERLAPPED *overlapped) {
  const BOOL ok = ReadFile(file, data, size, done, overlapped);
  read_bytes += *done;
  return ok;
}
BOOL injected_flush(HANDLE file) {
  if (failed_flushes) { --failed_flushes; SetLastError(ERROR_WRITE_FAULT); return FALSE; }
  return FlushFileBuffers(file);
}
#define ReadFile counted_read
#define WriteFile injected_write
#define FlushFileBuffers injected_flush
